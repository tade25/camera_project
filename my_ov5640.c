#define MY_OV5640_ARRAY_SIZE(x) sizeof(x) / sizeof((x)[0])

static int i2c_ov5640_write(struct i2c_client *clit, u16 reg_addr,
    u8* buf, u8 len
)
{
    struct i2c_msg msg;
    int ret;
    u8 data[256];

    if(!clit || !buf || len == 0 ||len > OV5640_I2C_WRITE_LEN)
        return -EINVAL;

    data[0] = (reg_addr >> 8) & 0xFF;
    data[1] = reg_addr;
    memcpy(&data[2], buf, len);

    msg.addr = clit->addr;
    msg.flags = 0;
    msg.len = len + 2;
    msg.buf = data;

    ret = i2c_transfer(clit->adapter, &msg, 1);
    
    return ((ret == 1) ? 0 : (ret < 0) ? ret : -EIO);
} 

static int i2c_ov5640_read(struct i2c_client *clit, u16 reg_addr,
    u8* buf, u8 len
)
{
    struct i2c_msg msg[2];
    int ret;
    u8 reg_buf[2];

    if(!clit || !buf || len == 0 || len > OV5640_I2C_READ_LEN)
        return -EINVAL;

    reg_buf[0] = (reg_addr >> 8) & 0xFF;
    reg_buf[1] = reg_addr;
    msg[0].addr = clit->addr;
    msg[0].flags = 0;
    msg[0].len = 2;
    msg[0].buf = reg_buf;

    msg[1].addr = clit->addr;
    msg[1].flags = I2C_M_RD;
    msg[1].len = len;
    msg[1].buf = buf;
    ret = i2c_transfer(clit->adapter, &msg[0], 2);

    return ((ret == 2) ? 0 : (ret < 0) ? ret : -EIO);
}

static void OV5640_Init(struct i2c_client *client)
{
    u8 i;
    u8 len;

    len = MY_OV5640_ARRAY_SIZE(ov5640_global_init_setting);
    for(i = 0;i < len;i++) {
        i2c_ov5640_write(client, ov5640_global_init_setting[i].reg,\
                &ov5640_global_init_setting[i].reg_val, 1);
    }

    len = MY_OV5640_ARRAY_SIZE(ov5640_init_setting_30fps_VGA);
    for(i = 0;i < len;i++) {
        i2c_ov5640_write(client, ov5640_init_setting_30fps_VGA[i].reg,\
                &ov5640_init_setting_30fps_VGA[i].reg_val, 1);
    }  
}

static int my_ov5640_probe(struct i2c_client *client, const struct i2c_device_id *id)
{
    u8 data[2] = {0};
    u16 chip_id = 0;
    struct gpio_desc* desc[2];

    desc[0] = gpiod_get(&client->dev, "reset", GPIOD_OUT_LOW);
    desc[1] = gpiod_get(&client->dev, "pwdn", GPIOD_OUT_LOW);

    /* 拉低PWDN, 拉低RESET, 延迟1ms */
    gpiod_set_value(desc[0], 0);
    gpiod_set_value(desc[1], 0);
    mdelay(1);

    /* 拉高RESET, 延迟20ms */
    gpiod_set_value(desc[0], 1);
    mdelay(20);

    (void)i2c_ov5640_read(client, OV5640_CHIP_ID_HIGH_BYTE, data, 2);
    chip_id = (u16)(((u16)data[0] << 8) | (u16)data[1]);
    printk("ov5640芯片id: 0x%x\n", chip_id);
    
    /* 初始化OV5640 */
    OV5640_Init(client);

    /* 进行垂直翻转 */
    data[0] = 0x46;
    i2c_ov5640_write(client, 0x3820, &data[0], 1);

    /* 关闭镜像 */
    data[0] = 0x01;
    i2c_ov5640_write(client, 0x3821, &data[0], 1);

    return 0;
}

